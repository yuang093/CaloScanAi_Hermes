-- 建立所有 Table、index、admin 帳號、365 句鼓勵語錄

-- ── UUID Extension ────────────────────────────────────────────────────────────
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ── Users Table ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS users (
    id          UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    username    VARCHAR(50) UNIQUE NOT NULL,
    email       VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role        VARCHAR(10) NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
    preferred_style VARCHAR(10),
    daily_calorie_limit INTEGER NOT NULL DEFAULT 2000,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_username ON users(username);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);

-- ── FoodLogs Table ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS food_logs (
    id          UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id     UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    image_url   VARCHAR(500),
    food_name   VARCHAR(255) NOT NULL,
    calories    INTEGER NOT NULL DEFAULT 0,
    source      VARCHAR(20) NOT NULL DEFAULT 'manual'
                CHECK (source IN ('ai_photo', 'nutrition_label', 'barcode', 'manual')),
    log_date    DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_food_logs_user_id ON food_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_food_logs_log_date ON food_logs(log_date);
CREATE INDEX IF NOT EXISTS idx_food_logs_user_date ON food_logs(user_id, log_date);

-- ── BarcodeDictionary Table ────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS barcode_dictionary (
    barcode     VARCHAR(50) PRIMARY KEY,
    food_name   VARCHAR(255) NOT NULL,
    calories    INTEGER NOT NULL DEFAULT 0,
    category    VARCHAR(100),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_barcode_category ON barcode_dictionary(category);

-- ── DailyQuotes Table ───────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS daily_quotes (
    id          INTEGER PRIMARY KEY CHECK (id BETWEEN 1 AND 365),
    quote_text  TEXT NOT NULL,
    author      VARCHAR(100),
    used_date   DATE
);

CREATE INDEX IF NOT EXISTS idx_daily_quotes_used_date ON daily_quotes(used_date);

-- ── Feedbacks Table ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS feedbacks (
    id          UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id     UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rating      INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    feedback_type VARCHAR(20) NOT NULL DEFAULT 'general'
                 CHECK (feedback_type IN ('feature', 'bug', 'general')),
    message     TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_feedbacks_user_id ON feedbacks(user_id);
CREATE INDEX IF NOT EXISTS idx_feedbacks_created_at ON feedbacks(created_at);

